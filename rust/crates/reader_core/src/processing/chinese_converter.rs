/// Chinese converter with built-in mapping tables.
pub struct ChineseConverter {
    s2t_map: &'static HashMap<char, char>,
    t2s_map: &'static HashMap<char, char>,
}

impl ChineseConverter {
    /// Create a new Chinese converter.
    pub fn new() -> Self {
        Self {
            s2t_map: &S2T_MAP,
            t2s_map: &T2S_MAP,
        }
    }

    /// Convert text using the specified mode.
    pub fn convert(&self, text: &str, mode: ConvertMode) -> String {
        match mode {
            ConvertMode::S2T => self.s2t(text),
            ConvertMode::T2S => self.t2s(text),
            ConvertMode::S2TW => self.s2t(text), // TW uses same mapping for now
            ConvertMode::S2HK => self.s2t(text), // HK uses same mapping for now
        }
    }

    /// Convert Simplified to Traditional Chinese.
    pub fn s2t(&self, text: &str) -> String {
        text.chars()
            .map(|c| self.s2t_map.get(&c).copied().unwrap_or(c))
            .collect()
    }

    /// Convert Traditional to Simplified Chinese.
    pub fn t2s(&self, text: &str) -> String {
        text.chars()
            .map(|c| self.t2s_map.get(&c).copied().unwrap_or(c))
            .collect()
    }

    /// Convert Simplified to Taiwan Traditional Chinese.
    pub fn s2tw(&self, text: &str) -> String {
        // Taiwan uses traditional characters with some differences
        // For now, use the same S2T mapping
        self.s2t(text)
    }

    /// Convert Simplified to Hong Kong Traditional Chinese.
    pub fn s2hk(&self, text: &str) -> String {
        // Hong Kong uses traditional characters with some differences
        // For now, use the same S2T mapping
        self.s2t(text)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_s2t_conversion() {
        let converter = ChineseConverter::new();
        let result = converter.s2t("简体字");
        assert_eq!(result, "簡體字");
    }

    #[test]
    fn test_t2s_conversion() {
        let converter = ChineseConverter::new();
        let result = converter.t2s("繁體字");
        assert_eq!(result, "繁体字");
    }

    #[test]
    fn test_s2tw_conversion() {
        let converter = ChineseConverter::new();
        let result = converter.s2tw("简体字");
        assert_eq!(result, "簡體字");
    }

    #[test]
    fn test_s2hk_conversion() {
        let converter = ChineseConverter::new();
        let result = converter.s2hk("简体字");
        assert_eq!(result, "簡體字");
    }

    #[test]
    fn test_empty_string() {
        let converter = ChineseConverter::new();
        let result = converter.s2t("");
        assert_eq!(result, "");
    }

    #[test]
    fn test_mixed_content() {
        let converter = ChineseConverter::new();
        let result = converter.s2t("Hello 你好 World");
        assert_eq!(result, "Hello 你好 World");
    }

    #[test]
    fn test_unmapped_chars() {
        let converter = ChineseConverter::new();
        let result = converter.s2t("abc123");
        assert_eq!(result, "abc123");
    }

    #[test]
    fn test_roundtrip() {
        let converter = ChineseConverter::new();
        let original = "简体字";
        let traditional = converter.s2t(original);
        let simplified = converter.t2s(&traditional);
        assert_eq!(simplified, original);
    }

    #[test]
    fn test_convert_method() {
        let converter = ChineseConverter::new();
        let result = converter.convert("简体字", ConvertMode::S2T);
        assert_eq!(result, "簡體字");
    }
}
